  @TempDir Path tempDir;

  private static final String DEFAULT_USERNAME = "testuser";
  private static final String DEFAULT_PASSWORD = "testpassword";

  private final ObjectMapper objectMapper = new ObjectMapper();

  @Test
  @DisplayName(
      "generateDefinitionsFile should create a non-empty definitions file "
          + "matching the content generated by buildDefinitionsContent")
  void generateDefinitionsFile_createsFileMatchingBuildDefinitionsContent() throws IOException {
    // Arrange
    MainConfiguration testConfiguration = buildDefaultMainConfiguration();
    RabbitMqConfigurationGenerator configurationGenerator =
        new RabbitMqConfigurationGenerator(testConfiguration);
    Path definitionsFilePath = tempDir.resolve("definitions.json");
    String expectedContent = configurationGenerator.buildDefinitionsContent();

    // Act
    configurationGenerator.generateDefinitionsFile(definitionsFilePath);

    // Assert
    assertThat(definitionsFilePath).exists().isNotEmptyFile();
    String fileContent = Files.readString(definitionsFilePath, StandardCharsets.UTF_8);
    assertThat(fileContent).isEqualToNormalizingNewlines(expectedContent);
  }

  @Test
  @DisplayName("buildDefinitionsContent should generate valid and parseable JSON")
  void buildDefinitionsContent_generatesValidAndParseableJson() {
    // Arrange
    MainConfiguration testConfiguration = buildDefaultMainConfiguration();
    RabbitMqConfigurationGenerator configurationGenerator =
        new RabbitMqConfigurationGenerator(testConfiguration);

    // Act & Assert
    assertThatCode(() -> objectMapper.readTree(configurationGenerator.buildDefinitionsContent()))
        .doesNotThrowAnyException();
  }

  @Test
  @DisplayName("buildDefinitionsContent should contain correct user authentication and permissions")
  void buildDefinitionsContent_containsCorrectUserAuthenticationAndPermissions()
      throws IOException {
    // Arrange
    MainConfiguration testConfiguration = buildDefaultMainConfiguration();
    RabbitMqConfigurationGenerator configurationGenerator =
        new RabbitMqConfigurationGenerator(testConfiguration);

    // Act
    String content = configurationGenerator.buildDefinitionsContent();
    JsonNode rootNode = objectMapper.readTree(content);

    // Assert Users
    JsonNode usersNode = rootNode.path("users");
    assertThat(usersNode).hasSize(1);
    JsonNode userNode = usersNode.get(0);
    assertThat(userNode.path("name").asText()).isEqualTo(DEFAULT_USERNAME);
    assertThat(userNode.path("password").asText()).isEqualTo(DEFAULT_PASSWORD);
    assertThat(userNode.path("tags").asText()).isEqualTo("administrator");

    // Assert Permissions
    JsonNode permissionsNode = rootNode.path("permissions");
    assertThat(permissionsNode.isArray()).isTrue();
    assertThat(permissionsNode).hasSize(1);
    JsonNode permissionNode = permissionsNode.get(0);
    assertThat(permissionNode.path("user").asText()).isEqualTo(DEFAULT_USERNAME);
    assertThat(permissionNode.path("vhost").asText()).isEqualTo("/");
    assertThat(permissionNode.path("configure").asText()).isEqualTo(".*");
    assertThat(permissionNode.path("write").asText()).isEqualTo(".*");
    assertThat(permissionNode.path("read").asText()).isEqualTo(".*");
  }

  @Test
  @DisplayName(
      "buildDefinitionsContent should contain correct queue definitions for bot types and strategies")
  void buildDefinitionsContent_containsCorrectQueues() throws IOException {
    // Arrange
    MainConfiguration testConfiguration = buildDefaultMainConfiguration();
    RabbitMqConfigurationGenerator configurationGenerator =
        new RabbitMqConfigurationGenerator(testConfiguration);

    // Act
    String content = configurationGenerator.buildDefinitionsContent();
    JsonNode rootNode = objectMapper.readTree(content);

    // Assert
    JsonNode queuesNode = rootNode.path("queues");
    assertThat(queuesNode.isArray()).isTrue();
    assertThat(queuesNode).hasSize(3);

    // Queue 1: bot_type.foo.orders.distributed
    JsonNode queue1 = queuesNode.get(0);
    assertThat(queue1.path("name").asText()).isEqualTo("bot_type.foo.orders.distributed");
    assertThat(queue1.path("vhost").asText()).isEqualTo("/");
    assertThat(queue1.path("durable").asBoolean()).isTrue();
    assertThat(queue1.path("auto_delete").asBoolean()).isFalse();
    assertThat(queue1.path("arguments").isEmpty()).isTrue(); // Not a stream queue

    // Queue 2: bot_type.bar.orders.distributed
    JsonNode queue2 = queuesNode.get(1);
    assertThat(queue2.path("name").asText()).isEqualTo("bot_type.bar.orders.distributed");
    assertThat(queue2.path("vhost").asText()).isEqualTo("/");
    assertThat(queue2.path("durable").asBoolean()).isTrue();
    assertThat(queue2.path("auto_delete").asBoolean()).isFalse();
    assertThat(queue2.path("arguments").isEmpty()).isTrue(); // Not a stream queue

    // Queue 3: bot_type.bar.orders.broadcast (stream queue)
    JsonNode queue3 = queuesNode.get(2);
    assertThat(queue3.path("name").asText()).isEqualTo("bot_type.bar.orders.broadcast");
    assertThat(queue3.path("vhost").asText()).isEqualTo("/");
    assertThat(queue3.path("durable").asBoolean()).isTrue();
    assertThat(queue3.path("auto_delete").asBoolean()).isFalse();
    assertThat(queue3.path("arguments").path("x-queue-type").asText()).isEqualTo("stream");
  }

