  @Test
  @DisplayName(
      "buildDefinitionsContent should generate correct JSON when no bot types are configured")
  void buildDefinitionsContent_noBotTypes_generatesCorrectJson() throws IOException {
    // Arrange
    MainConfiguration emptyConfiguration = new MainConfiguration();
    RabbitMqConfiguration rabbitConfiguration = new RabbitMqConfiguration();
    rabbitConfiguration.setUsername(DEFAULT_USERNAME);
    rabbitConfiguration.setPassword(DEFAULT_PASSWORD);
    emptyConfiguration.setBrokerConfiguration(rabbitConfiguration);
    emptyConfiguration.setBotTypes(Collections.emptyMap());

    RabbitMqConfigurationGenerator configurationGenerator =
        new RabbitMqConfigurationGenerator(emptyConfiguration);

    // Act
    String content = configurationGenerator.buildDefinitionsContent();
    JsonNode rootNode = objectMapper.readTree(content);

    // Assert base structure
    assertThat(rootNode.path("vhosts")).hasSize(1);
    assertThat(rootNode.path("users")).hasSize(1);
    assertThat(rootNode.path("permissions")).hasSize(1);
    assertThat(rootNode.path("exchanges")).hasSize(2); // Still has default exchanges

    // Assert that queues and bindings are empty arrays
    assertThat(rootNode.path("queues")).isEmpty();
    assertThat(rootNode.path("bindings")).isEmpty();

    // Assert user details are still present
    assertThat(rootNode.path("users").get(0).path("name").asText()).isEqualTo(DEFAULT_USERNAME);
    assertThat(rootNode.path("users").get(0).path("password").asText()).isEqualTo(DEFAULT_PASSWORD);
  }

  @Test
  @DisplayName(
      "buildDefinitionsContent should correctly handle a single bot type with mixed strategies")
  void buildDefinitionsContent_singleBotTypeMixedStrategies_generatesCorrectJson()
      throws IOException {
    // Arrange
    MainConfiguration config = new MainConfiguration();
    RabbitMqConfiguration rabbitConfig = new RabbitMqConfiguration();
    rabbitConfig.setUsername(DEFAULT_USERNAME);
    rabbitConfig.setPassword(DEFAULT_PASSWORD);
    config.setBrokerConfiguration(rabbitConfig);

    BotTypeConfiguration singleBotType = new BotTypeConfiguration();
    singleBotType.setId("singleBot");

    BotSubscribeConfiguration distributedSub = new BotSubscribeConfiguration();
    distributedSub.setKey("dist_key");
    distributedSub.setStrategy(RoutingStrategy.DISTRIBUTED);

    BotSubscribeConfiguration broadcastSub = new BotSubscribeConfiguration();
    broadcastSub.setKey("broadcast_key");
    broadcastSub.setStrategy(RoutingStrategy.BROADCAST);

    singleBotType.setSubscribeConfigurations(List.of(distributedSub, broadcastSub));
    config.setBotTypes(Map.of("singleBot", singleBotType));

    RabbitMqConfigurationGenerator generator = new RabbitMqConfigurationGenerator(config);

    // Act
    String content = generator.buildDefinitionsContent();
    JsonNode rootNode = objectMapper.readTree(content);

    // Assert Queues
    JsonNode queuesNode = rootNode.path("queues");
    assertThat(queuesNode).hasSize(2);

    JsonNode distributedQueue = queuesNode.get(0);
    assertThat(distributedQueue.path("name").asText())
        .isEqualTo("bot_type.singleBot.orders.distributed");
    assertThat(distributedQueue.path("arguments").isEmpty()).isTrue();

    JsonNode broadcastQueue = queuesNode.get(1);
    assertThat(broadcastQueue.path("name").asText())
        .isEqualTo("bot_type.singleBot.orders.broadcast");
    assertThat(broadcastQueue.path("arguments").path("x-queue-type").asText()).isEqualTo("stream");

    // Assert Bindings
    JsonNode bindingsNode = rootNode.path("bindings");
    assertThat(bindingsNode).hasSize(2);

    JsonNode distributedBinding = bindingsNode.get(0);
    assertThat(distributedBinding.path("source").asText()).isEqualTo(ORDER_EXCHANGE);
    assertThat(distributedBinding.path("destination").asText())
        .isEqualTo("bot_type.singleBot.orders.distributed");
    assertThat(distributedBinding.path("routing_key").asText()).isEqualTo("dist_key");

    JsonNode broadcastBinding = bindingsNode.get(1);
    assertThat(broadcastBinding.path("source").asText()).isEqualTo(ORDER_EXCHANGE);
    assertThat(broadcastBinding.path("destination").asText())
        .isEqualTo("bot_type.singleBot.orders.broadcast");
    assertThat(broadcastBinding.path("routing_key").asText()).isEqualTo("broadcast_key");
  }

  private MainConfiguration buildDefaultMainConfiguration() {
    MainConfiguration configuration = new MainConfiguration();

    RabbitMqConfiguration rabbitConfiguration = new RabbitMqConfiguration();
    rabbitConfiguration.setUsername(DEFAULT_USERNAME);
    rabbitConfiguration.setPassword(DEFAULT_PASSWORD);

    configuration.setBrokerConfiguration(rabbitConfiguration);
    configuration.setBotTypes(buildBotConfigurations());
    return configuration;
  }

  private Map<String, BotTypeConfiguration> buildBotConfigurations() {
    var fooKeySubscription = buildSubscription("foo_key", RoutingStrategy.DISTRIBUTED);
    var barKeySubscription = buildSubscription("bar_key", RoutingStrategy.DISTRIBUTED);
    var quxKeySubscription = buildSubscription("qux_key", RoutingStrategy.BROADCAST);

    BotTypeConfiguration fooBotType = new BotTypeConfiguration();
    fooBotType.setId("foo");
    fooBotType.setSubscribeConfigurations(List.of(fooKeySubscription, barKeySubscription));

    BotTypeConfiguration barBotType = new BotTypeConfiguration();
    barBotType.setId("bar");
    barBotType.setSubscribeConfigurations(List.of(barKeySubscription, quxKeySubscription));

    Map<String, BotTypeConfiguration> bots =
        new LinkedHashMap<>(); // Use LinkedHashMap for predictable order in tests
    bots.put("foo", fooBotType);
    bots.put("bar", barBotType);
    return bots;
  }

  private BotSubscribeConfiguration buildSubscription(String key, RoutingStrategy strategy) {
    BotSubscribeConfiguration subscribeConfiguration = new BotSubscribeConfiguration();
    subscribeConfiguration.setKey(key);
    subscribeConfiguration.setStrategy(strategy);
    return subscribeConfiguration;
  }
